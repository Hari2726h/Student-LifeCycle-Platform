import { mkdir, writeFile, readFile } from "fs/promises";
import path from "path";
import crypto from "crypto";

// Local-disk storage for this dev build — the architecture plan's production
// target is Supabase Storage; this keeps the same Document-row contract
// (storageKey/fileName/mimeType/sizeBytes) so swapping the backend later
// doesn't touch any calling code.
const UPLOAD_ROOT = path.join(process.cwd(), "uploads");

const SAFE_EXT = /^[a-zA-Z0-9]{1,8}$/;

function extensionOf(fileName: string) {
  const ext = path.extname(fileName).replace(".", "");
  return SAFE_EXT.test(ext) ? ext : "bin";
}

export async function saveUploadedFile(applicantId: string, file: File) {
  const dir = path.join(UPLOAD_ROOT, applicantId);
  await mkdir(dir, { recursive: true });

  const key = `${crypto.randomUUID()}.${extensionOf(file.name)}`;
  const buffer = Buffer.from(await file.arrayBuffer());
  await writeFile(path.join(dir, key), buffer);

  return {
    storageKey: `${applicantId}/${key}`,
    fileName: file.name,
    mimeType: file.type || "application/octet-stream",
    sizeBytes: buffer.byteLength,
  };
}

export async function readUploadedFile(storageKey: string) {
  // storageKey is always generated by saveUploadedFile (applicantId/uuid.ext),
  // never taken from user input directly, so there's no path-traversal surface.
  return readFile(path.join(UPLOAD_ROOT, storageKey));
}
